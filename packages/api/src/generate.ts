import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { basename, dirname, join, parse, relative, resolve, sep } from "node:path";
import { generate as generateOrval } from "orval";
import * as prettier from "prettier";
import type { OpenAPIV3 } from "@scalar/openapi-types";
import { validateConfig } from "./config.js";
import type { CodegenConfig, GenerateOptions, GenerateResult } from "./config.js";
import { renderApi } from "./render-api.js";
import { renderQueryFiles } from "./render-queries.js";
import { renderProblems } from "./render-problems.js";
import { validateExports } from "./validate-exports.js";
import { collectOperations, identifier } from "./openapi.js";
import { hasErrorCode, isWithin, listFiles, outputFiles } from "./files.js";

/** Generated clients import this package unless the config names its own request module. */
const defaultRequestModule = "lit-canon-fetch";

/**
 * Orval reads the apiFetch signature from a mutator file. renderApi rewrites the generated
 * import, so this stub only has to match the signature exported by lit-canon-fetch.
 */
const mutatorStub = `export type ApiRequestOptions = Omit<RequestInit, "body"> & {
  body?: unknown;
  query?: object;
};

export function apiFetch<T>(url: string, options?: ApiRequestOptions): Promise<T> {
  return Promise.reject(new Error(url));
}
`;

const tempPrefix = "lit-canon-api-";

function resourceNamespace(tag: string): string {
  return tag.replace(/-([a-z0-9])/g, (_, character: string) => character.toUpperCase());
}

function importPath(fromDirectory: string, target: string): string {
  let path = relative(fromDirectory, target).split(sep).join("/");
  path = path.replace(/\.(?:[cm]?ts|[cm]?js)$/, "");
  return path.startsWith(".") ? path : `./${path}`;
}

export async function generate(
  config: CodegenConfig,
  options: GenerateOptions = {},
): Promise<GenerateResult> {
  validateConfig(config);
  const cwd = resolve(options.cwd ?? process.cwd());
  const workspace = resolve(cwd, config.workspace ?? ".");
  const input = resolve(cwd, config.input);
  const output = resolve(cwd, config.output);
  const requestPath = config.request ? resolve(cwd, config.request.path) : null;
  if (
    output === parse(output).root ||
    isWithin(output, cwd) ||
    isWithin(output, input) ||
    (requestPath !== null && isWithin(output, requestPath))
  ) {
    throw new Error(`Output must be a dedicated generated directory: ${output}`);
  }
  const preserved = new Set(config.preserveDirectories ?? []);
  for (const name of preserved) {
    if (
      typeof name !== "string" ||
      !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(name) ||
      name === "index.ts"
    ) {
      throw new Error(`Preserved directories must be top-level directory names: ${name}`);
    }
  }
  const existing = await outputFiles(output, preserved);
  const spec = JSON.parse(await readFile(input, "utf8")) as OpenAPIV3.Document;
  if (!spec || !/^3\./.test(spec.openapi ?? "") || !spec.info || !spec.paths) {
    throw new Error("Input must be an OpenAPI 3 JSON document with info and paths");
  }
  const { operationsByTag, mutationOperations } = collectOperations(spec, config);
  const tags = [...operationsByTag.keys()].sort();
  const namespaces = new Set();
  for (const tag of tags) {
    if (preserved.has(tag)) {
      throw new Error(`Generated resource conflicts with a preserved directory: ${tag}`);
    }
    const namespace = identifier(resourceNamespace(tag), "resource namespace");
    if (namespaces.has(namespace)) {
      throw new Error(`Duplicate resource namespace: ${namespace}`);
    }
    namespaces.add(namespace);
  }
  const header = [
    "/**",
    " * Generated by lit-canon-api. Do not edit manually.",
    ` * ${String(spec.info.title).replace(/\*\//g, "* /")}`,
    ` * OpenAPI spec version: ${String(spec.info.version).replace(/\*\//g, "* /")}`,
    " */",
  ].join("\n");
  const prettierOptions = {
    ...(await prettier.resolveConfig(join(cwd, "lit-canon-api.config.ts"))),
    ...config.prettier,
    parser: "typescript",
  };
  const format = (source: string) => prettier.format(source, prettierOptions);
  await mkdir(dirname(output), { recursive: true });
  const temp = await mkdtemp(join(dirname(output), `.${basename(output)}.${tempPrefix}`));
  const staged = join(temp, "generated");
  await mkdir(staged);
  let cleanup = true;
  try {
    const mutatorPath = requestPath ?? join(temp, "mutator.ts");
    if (!requestPath) {
      await writeFile(mutatorPath, mutatorStub);
    }
    for (const tag of tags) {
      const resourceDir = join(staged, tag);
      const requestImport = requestPath
        ? importPath(join(output, tag), requestPath)
        : defaultRequestModule;
      const operations = operationsByTag.get(tag)!;
      await generateOrval(
        {
          input: { target: input, filters: { tags: [tag] } },
          output: {
            mode: "split",
            target: join(resourceDir, "api.ts"),
            schemas: false,
            client: "fetch",
            override: {
              mutator: { path: mutatorPath, name: "apiFetch" },
              fetch: { includeHttpResponseReturnType: false, forceSuccessResponse: true },
            },
          },
        },
        workspace,
        { throwOnError: true, logLevel: "error" },
      );
      const apiSource = renderApi(
        await readFile(join(resourceDir, "api.ts"), "utf8"),
        operations,
        header,
        requestImport,
      );
      await writeFile(join(resourceDir, "api.ts"), await format(apiSource));
      const generatedModels = join(resourceDir, "api.schemas.ts");
      let modelsSource;
      try {
        modelsSource = await readFile(generatedModels, "utf8");
        modelsSource = modelsSource.replace(/^\/\*\*[\s\S]*?\*\//, header);
        await rm(generatedModels);
      } catch (error) {
        if (!hasErrorCode(error, "ENOENT")) {
          throw error;
        }
        modelsSource = `${header}\n\nexport {};\n`;
      }
      if (!/^export\s/m.test(modelsSource)) {
        modelsSource += "\nexport {};\n";
      }
      await writeFile(join(resourceDir, "models.ts"), await format(modelsSource));
      const problems = renderProblems(
        tag,
        operations,
        header,
        requestImport,
        config.problems === true,
      );
      if (problems) {
        await writeFile(join(resourceDir, "problems.ts"), await format(problems));
      }
      const { queries, mutations } = renderQueryFiles(tag, operations, apiSource, header, {
        namespace: resourceNamespace(tag),
        mutationOperations,
      });
      if (queries) {
        await writeFile(join(resourceDir, "queries.ts"), await format(queries));
      }
      if (mutations) {
        await writeFile(join(resourceDir, "mutations.ts"), await format(mutations));
      }
      const runtimeExports = config.request?.exports ?? ["ApiError"];
      const runtimeTypeExports = config.request?.typeExports ?? ["ApiProblem", "ApiRequestOptions"];
      const barrel = [
        header,
        "",
        'export * from "./api";',
        'export * from "./models";',
        ...(problems ? ['export * from "./problems";'] : []),
        ...(queries ? ['export * from "./queries";'] : []),
        ...(mutations ? ['export * from "./mutations";'] : []),
        ...(runtimeExports.length
          ? [
              `export { ${runtimeExports.map((name) => identifier(name, "request export")).join(", ")} } from ${JSON.stringify(requestImport)};`,
            ]
          : []),
        ...(runtimeTypeExports.length
          ? [
              `export type { ${runtimeTypeExports.map((name) => identifier(name, "request type export")).join(", ")} } from ${JSON.stringify(requestImport)};`,
            ]
          : []),
        "",
      ].join("\n");
      validateExports({
        "api.ts": apiSource,
        "models.ts": modelsSource,
        ...(problems ? { "problems.ts": problems } : {}),
        ...(queries ? { "queries.ts": queries } : {}),
        ...(mutations ? { "mutations.ts": mutations } : {}),
        "request exports": barrel,
      });
      await writeFile(join(resourceDir, "index.ts"), await format(barrel));
    }
    await writeFile(
      join(staged, "index.ts"),
      await format(
        `${header}\n\n${tags.map((tag) => `export * as ${resourceNamespace(tag)} from "./${tag}";`).join("\n")}\n`,
      ),
    );
    const files = await listFiles(staged);
    if (options.check) {
      const changed = [...new Set([...files.keys(), ...existing.keys()])].filter(
        (name) => files.get(name) !== existing.get(name),
      );
      if (changed.length) {
        throw new Error(
          `Generated client is out of date:\n${changed.sort().join("\n")}\nRun lit-canon-api generate to regenerate it.`,
        );
      }
    } else {
      // Check ownership again immediately before replacing the generated directory.
      await outputFiles(output, preserved);
      const backup = join(temp, "previous");
      let moved = false;
      try {
        await rename(output, backup);
        moved = true;
      } catch (error) {
        if (!hasErrorCode(error, "ENOENT")) {
          throw error;
        }
      }
      const movedDirectories: string[] = [];
      try {
        if (moved) {
          for (const name of preserved) {
            try {
              // Move the current tree at commit time instead of copying a stale snapshot.
              await rename(join(backup, name), join(staged, name));
              movedDirectories.push(name);
            } catch (error) {
              if (!hasErrorCode(error, "ENOENT")) {
                throw error;
              }
            }
          }
        }
        await rename(staged, output);
      } catch (error) {
        if (moved) {
          try {
            for (const name of movedDirectories.reverse()) {
              await rename(join(staged, name), join(backup, name));
            }
            await rename(backup, output);
          } catch (restoreError) {
            cleanup = false;
            throw new AggregateError(
              [error, restoreError],
              `Could not replace or restore the client. Previous files are preserved inside ${temp}`,
            );
          }
        }
        throw error;
      }
    }
    return { output, tags, files: [...files.keys()].sort() };
  } finally {
    // temp is the absolute, dedicated path returned by mkdtemp above.
    if (
      dirname(temp) !== dirname(output) ||
      !basename(temp).startsWith(`.${basename(output)}.${tempPrefix}`)
    ) {
      throw new Error(`Unexpected temporary directory: ${temp}`);
    }
    if (cleanup) {
      await rm(temp, { recursive: true, force: true });
    }
  }
}
